#!/usr/bin/env python3
"""Score persona responses with the official trait and coherence judge protocol."""

from __future__ import annotations

import argparse
import asyncio
from collections import deque
import json
import math
import os
import time
from pathlib import Path

from _bootstrap import ROOT


def _resolve(path: str | Path) -> Path:
    path = Path(path)
    return path if path.is_absolute() else ROOT / path


class RollingTokenLimiter:
    """Conservatively throttle estimated prompt tokens over a rolling minute."""

    def __init__(self, *, budget: int, characters_per_token: float) -> None:
        if budget <= 0 or characters_per_token <= 0:
            raise ValueError("rate-limit budget and characters-per-token must be positive")
        self.budget = budget
        self.characters_per_token = characters_per_token
        self.events: deque[tuple[float, int]] = deque()
        self.used = 0
        self.lock = asyncio.Lock()

    def estimate(self, prompt: str) -> int:
        # The 32-token allowance covers message framing and the single output
        # token. Dividing by 2.5 is deliberately conservative for English.
        return max(1, math.ceil(len(prompt) / self.characters_per_token) + 32)

    async def acquire(self, prompt: str) -> None:
        requested = self.estimate(prompt)
        if requested > self.budget:
            raise ValueError("one judge prompt exceeds the configured minute token budget")
        while True:
            async with self.lock:
                now = time.monotonic()
                while self.events and now - self.events[0][0] >= 60.0:
                    _, expired = self.events.popleft()
                    self.used -= expired
                if self.used + requested <= self.budget:
                    self.events.append((now, requested))
                    self.used += requested
                    return
                wait_seconds = max(0.05, 60.0 - (now - self.events[0][0]) + 0.05)
            await asyncio.sleep(wait_seconds)


async def main_async(args) -> None:
    from openai import AsyncOpenAI
    from tqdm.auto import tqdm

    from refusal_circuit.paths import write_json
    from refusal_circuit.persona import (
        COHERENCE_PROMPT,
        aggregate_numeric_logprobs,
        read_jsonl,
        sha256_file,
        write_jsonl,
    )

    if not os.environ.get("OPENAI_API_KEY"):
        raise RuntimeError(
            "OPENAI_API_KEY is required for canonical Persona Vectors filtering. "
            "Do not substitute an unvalidated local judge for paper evidence."
        )
    config = json.loads(args.config.read_text(encoding="utf-8"))
    judge_cfg = config["judge"]
    protocol_field = args.protocol_field or (
        "generation_protocol_id" if args.artifact == "extract" else "steering_protocol_id"
    )
    official_root = _resolve(config["paths"]["official_root"])
    trait_data = json.loads((official_root / f"{args.artifact}.json").read_text(encoding="utf-8"))
    trait_prompt = trait_data["eval_prompt"]
    input_path = _resolve(args.input)
    output_path = _resolve(args.output)
    rows = read_jsonl(input_path)
    if not rows:
        raise ValueError(f"no rows in {input_path}")
    if any(row.get(protocol_field) != config["protocol_id"] for row in rows):
        raise ValueError(
            "input was not generated by the frozen Persona Vectors protocol; "
            "regenerate it before spending money on canonical judging"
        )
    generation_metadata_path = input_path.parent / "metadata.json"
    generation_metadata = json.loads(generation_metadata_path.read_text(encoding="utf-8"))
    if generation_metadata.get(protocol_field) != config["protocol_id"]:
        raise ValueError("input metadata protocol ID does not match the frozen config")
    recorded = {item["path"]: item["sha256"] for item in generation_metadata["outputs"]}
    relative_input = str(input_path.relative_to(ROOT))
    if recorded.get(relative_input) != sha256_file(input_path):
        raise ValueError("generation input hash differs from its completed metadata")
    existing = {}
    if output_path.exists():
        if args.overwrite:
            output_path.unlink()
        elif args.resume:
            cached = read_jsonl(output_path)
            existing = {row["record_id"]: row for row in cached}
            if len(existing) != len(cached):
                raise ValueError(f"duplicate record IDs in {output_path}")
        else:
            raise FileExistsError(f"{output_path} exists; pass --resume or --overwrite")

    reused_count = 0
    if args.reuse_output is not None:
        reuse_path = _resolve(args.reuse_output)
        reusable_rows = read_jsonl(reuse_path)
        reusable = {row["record_id"]: row for row in reusable_rows}
        if len(reusable) != len(reusable_rows):
            raise ValueError(f"duplicate reusable record IDs in {reuse_path}")

        def semantic_key(row: dict) -> tuple:
            return (
                row.get("condition"),
                row.get("question_id"),
                row.get("question"),
                row.get("system_prompt"),
                row.get("answer"),
                row.get("decoding"),
                row.get("model"),
                row.get("model_revision"),
            )

        reusable_by_content = {}
        for old in reusable_rows:
            key = semantic_key(old)
            if key in reusable_by_content:
                raise ValueError(f"ambiguous reusable judged content in {reuse_path}")
            reusable_by_content[key] = old
        inputs_by_id = {row["record_id"]: row for row in rows}
        judge_fields = (
            "trait_score",
            "trait_numeric_mass",
            "coherence_score",
            "coherence_numeric_mass",
            "judge_model",
            "judge_protocol",
            "trait_judge_request",
            "coherence_judge_request",
        )
        for record_id, current in inputs_by_id.items():
            if record_id in existing:
                continue
            old = reusable.get(record_id) or reusable_by_content.get(semantic_key(current))
            if old is None:
                continue
            if old.get("question") != current.get("question") or old.get("answer") != current.get("answer"):
                raise ValueError(f"Refusing mismatched reused judge row {record_id}")
            copied = dict(current)
            for field in judge_fields:
                if field in old:
                    copied[field] = old[field]
            copied["judge_reused_from"] = str(reuse_path.relative_to(ROOT))
            copied["judge_reused_record_id"] = old["record_id"]
            write_jsonl(output_path, [copied], mode="a")
            existing[record_id] = copied
            reused_count += 1

    client = AsyncOpenAI()
    semaphore = asyncio.Semaphore(args.concurrency or int(judge_cfg["concurrency"]))
    model = args.model or judge_cfg["model"]
    if model != judge_cfg["model"]:
        raise ValueError("canonical judging requires the frozen dated GPT-4.1-mini snapshot")
    max_retries = int(judge_cfg["max_retries"])
    limiter = RollingTokenLimiter(
        budget=int(judge_cfg["estimated_token_budget_per_minute"]),
        characters_per_token=float(judge_cfg["estimated_characters_per_token"]),
    )

    async def score(prompt: str) -> tuple[float | None, float, dict]:
        messages = [{"role": "user", "content": prompt}]
        for attempt in range(max_retries):
            try:
                await limiter.acquire(prompt)
                async with semaphore:
                    response = await client.chat.completions.create(
                        model=model,
                        messages=messages,
                        max_tokens=1,
                        temperature=0,
                        logprobs=True,
                        top_logprobs=int(judge_cfg["top_logprobs"]),
                        seed=int(judge_cfg["seed"]),
                    )
                candidates = response.choices[0].logprobs.content[0].top_logprobs
                probabilities = {candidate.token: math.exp(candidate.logprob) for candidate in candidates}
                numeric_mass = 0.0
                for token, probability in probabilities.items():
                    try:
                        value = int(token)
                    except ValueError:
                        continue
                    if 0 <= value <= 100:
                        numeric_mass += probability
                usage = response.usage.model_dump() if response.usage is not None else None
                return aggregate_numeric_logprobs(probabilities), numeric_mass, {
                    "response_id": response.id,
                    "created": response.created,
                    "usage": usage,
                }
            except Exception:
                if attempt + 1 == max_retries:
                    raise
                await asyncio.sleep(min(2**attempt, 60) + 0.1 * (attempt % 5))
        raise AssertionError("unreachable")

    async def judge_row(row: dict) -> dict:
        trait_score, trait_mass, trait_request = await score(
            trait_prompt.format(question=row["question"], answer=row["answer"])
        )
        coherence_score, coherence_mass, coherence_request = await score(
            COHERENCE_PROMPT.format(question=row["question"], answer=row["answer"])
        )
        output = dict(row)
        output.update(
            {
                "trait_score": trait_score,
                "trait_numeric_mass": trait_mass,
                "coherence_score": coherence_score,
                "coherence_numeric_mass": coherence_mass,
                "judge_model": model,
                "judge_protocol": "top20_expected_0_100",
                "trait_judge_request": trait_request,
                "coherence_judge_request": coherence_request,
            }
        )
        return output

    pending = [row for row in rows if row["record_id"] not in existing]
    tasks = [asyncio.create_task(judge_row(row)) for row in pending]
    with tqdm(total=len(tasks), desc="judge persona responses") as progress:
        for task in asyncio.as_completed(tasks):
            judged = await task
            write_jsonl(output_path, [judged], mode="a")
            progress.update(1)
    final = read_jsonl(output_path)
    if len(final) != len(rows) or len({row["record_id"] for row in final}) != len(rows):
        raise RuntimeError(f"incomplete judged output: {len(final)}/{len(rows)}")
    metadata = {
        "schema_version": 1,
        "status": "complete",
        "canonical_protocol": True,
        protocol_field: config["protocol_id"],
        "input": str(input_path.relative_to(ROOT)),
        "input_sha256": sha256_file(input_path),
        "output": str(output_path.relative_to(ROOT)),
        "output_sha256": sha256_file(output_path),
        "rows": len(final),
        "judge_model": model,
        "request_concurrency": args.concurrency or int(judge_cfg["concurrency"]),
        "estimated_token_budget_per_minute": int(
            judge_cfg["estimated_token_budget_per_minute"]
        ),
        "rubric_artifact": args.artifact,
        "trait_score_failures": sum(row["trait_score"] is None for row in final),
        "coherence_score_failures": sum(row["coherence_score"] is None for row in final),
        "reused_judged_rows": reused_count,
        "new_judged_rows": len(final) - reused_count,
    }
    write_json(output_path.with_suffix(".metadata.json"), metadata)
    print(json.dumps(metadata, indent=2))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=ROOT / "configs/qwen_sycophancy.json")
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--model", default=None)
    parser.add_argument("--artifact", choices=("extract", "eval"), default="extract")
    parser.add_argument(
        "--protocol-field",
        choices=("generation_protocol_id", "steering_protocol_id", "behavior_protocol_id"),
        default=None,
        help="Input/metadata provenance field; behavioral pilots use behavior_protocol_id.",
    )
    parser.add_argument("--concurrency", type=int, default=None)
    parser.add_argument("--resume", action="store_true")
    parser.add_argument(
        "--reuse-output",
        type=Path,
        default=None,
        help="Reuse already judged rows only when record ID, question, and answer match exactly.",
    )
    parser.add_argument("--overwrite", action="store_true")
    args = parser.parse_args()
    if args.resume and args.overwrite:
        raise ValueError("--resume and --overwrite are mutually exclusive")
    asyncio.run(main_async(args))


if __name__ == "__main__":
    main()
